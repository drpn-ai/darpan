        return factId ? BY_ID.get(factId) : null
    }

    /** A fact whose id is not in {@code heard}, chosen at random; null once every fact has been heard. */
    static String pickUnheard(Set<String> heard, Random random) {
        List<String> fresh = BY_ID.keySet().findAll { !(heard?.contains(it)) } as List<String>
        return fresh ? fresh[random.nextInt(fresh.size())] : null
    }
